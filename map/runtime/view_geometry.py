"""Task-agnostic geometry for registering a rendered view to its source image.

The contract is intentionally explicit:

* ``source_roi_xyxy_px`` is a continuous, half-open rectangle in source pixels.
* ``content_rect_canvas_xyxy_px`` is the canvas rectangle occupied by that ROI.
* ``local1000`` coordinates are always normalized against the *whole canvas*.
* ``canvas_to_source`` is the affine transform that maps displayed content back
  to the source image.

Coordinates supplied by a caller are never clipped or guessed.  In particular,
a local point or box that falls wholly or partly in canvas padding is rejected.
The right and bottom rectangle endpoints are valid geometric endpoints even
though the corresponding pixel arrays use half-open indexing.

This module deliberately has no task routing and no benchmark dependencies.
"""

from __future__ import annotations

from dataclasses import dataclass
import math
from numbers import Real
from typing import Any, Mapping, Sequence


LOCAL1000_SCALE = 1000.0
LOCAL_COORDINATE_PROTOCOL = "canvas_base1000_xy"
BOUNDARY_CONVENTION = "continuous_xyxy_with_half_open_pixel_extents"


class ViewGeometryError(ValueError):
    """Base class for invalid view geometry or coordinate inputs."""


class CoordinateRangeError(ViewGeometryError):
    """A coordinate is outside its explicitly declared domain."""


class PaddingCoordinateError(ViewGeometryError):
    """A coordinate touches canvas area that does not contain source content."""


class GeometryConsistencyError(ViewGeometryError):
    """The ROI, content rectangle, and affine transform disagree."""


def _finite_float(value: Real, *, name: str) -> float:
    if isinstance(value, bool) or not isinstance(value, Real):
        raise TypeError(f"{name} must be a real number, got {type(value).__name__}")
    result = float(value)
    if not math.isfinite(result):
        raise CoordinateRangeError(f"{name} must be finite, got {value!r}")
    return result


def _values(value: Sequence[Real], *, length: int, name: str) -> tuple[float, ...]:
    if isinstance(value, (str, bytes)):
        raise TypeError(f"{name} must be a numeric sequence of length {length}")
    try:
        raw = tuple(value)
    except TypeError as exc:
        raise TypeError(f"{name} must be a numeric sequence of length {length}") from exc
    if len(raw) != length:
        raise ViewGeometryError(f"{name} must have length {length}, got {len(raw)}")
    return tuple(_finite_float(item, name=f"{name}[{index}]") for index, item in enumerate(raw))


def _strict_base1000(value: float, *, name: str) -> float:
    if value < 0.0 or value > LOCAL1000_SCALE:
        raise CoordinateRangeError(
            f"{name}={value!r} is outside the declared local1000 range [0, 1000]"
        )
    return value


def _snap_generated_endpoint(value: float, upper: float) -> float:
    """Remove floating-point noise only from values generated by this module."""

    tolerance = 1e-10 * max(1.0, abs(upper))
    if abs(value) <= tolerance:
        return 0.0
    if abs(value - upper) <= tolerance:
        return upper
    return value


@dataclass(frozen=True)
class Size2D:
    """Positive width and height in pixels."""

    width: float
    height: float

    def __post_init__(self) -> None:
        width = _finite_float(self.width, name="width")
        height = _finite_float(self.height, name="height")
        if width <= 0.0 or height <= 0.0:
            raise GeometryConsistencyError(
                f"size must be positive, got width={width}, height={height}"
            )
        object.__setattr__(self, "width", width)
        object.__setattr__(self, "height", height)

    @classmethod
    def from_pair(cls, value: Sequence[Real], *, name: str = "size") -> "Size2D":
        width, height = _values(value, length=2, name=name)
        return cls(width, height)

    def as_pair(self) -> tuple[float, float]:
        return self.width, self.height


@dataclass(frozen=True)
class RectXYXY:
    """A non-empty continuous rectangle expressed as ``(x0, y0, x1, y1)``."""

    x0: float
    y0: float
    x1: float
    y1: float

    def __post_init__(self) -> None:
        values = tuple(
            _finite_float(value, name=name)
            for name, value in zip(("x0", "y0", "x1", "y1"), self.as_tuple())
        )
        x0, y0, x1, y1 = values
        if x1 <= x0 or y1 <= y0:
            raise GeometryConsistencyError(
                "rectangle must have strictly positive width and height, "
                f"got {(x0, y0, x1, y1)!r}"
            )
        object.__setattr__(self, "x0", x0)
        object.__setattr__(self, "y0", y0)
        object.__setattr__(self, "x1", x1)
        object.__setattr__(self, "y1", y1)

    @classmethod
    def from_sequence(cls, value: Sequence[Real], *, name: str = "rect") -> "RectXYXY":
        return cls(*_values(value, length=4, name=name))

    @property
    def width(self) -> float:
        return self.x1 - self.x0

    @property
    def height(self) -> float:
        return self.y1 - self.y0

    def as_tuple(self) -> tuple[float, float, float, float]:
        return self.x0, self.y0, self.x1, self.y1

    def contains_point(self, point: tuple[float, float]) -> bool:
        x, y = point
        return self.x0 <= x <= self.x1 and self.y0 <= y <= self.y1

    def contains_rect(self, rect: "RectXYXY") -> bool:
        return (
            self.x0 <= rect.x0
            and self.y0 <= rect.y0
            and rect.x1 <= self.x1
            and rect.y1 <= self.y1
        )


@dataclass(frozen=True)
class Affine2D:
    """An invertible affine transform stored as a row-major 2-by-3 matrix."""

    xx: float
    xy: float
    x_offset: float
    yx: float
    yy: float
    y_offset: float

    def __post_init__(self) -> None:
        names = ("xx", "xy", "x_offset", "yx", "yy", "y_offset")
        for name in names:
            object.__setattr__(self, name, _finite_float(getattr(self, name), name=name))
        if abs(self.determinant) <= 1e-15:
            raise GeometryConsistencyError("canvas_to_source affine must be invertible")

    @property
    def determinant(self) -> float:
        return self.xx * self.yy - self.xy * self.yx

    @classmethod
    def from_rows(cls, rows: Sequence[Sequence[Real]]) -> "Affine2D":
        try:
            row_values = tuple(rows)
        except TypeError as exc:
            raise TypeError("affine must be a 2-by-3 numeric sequence") from exc
        if len(row_values) != 2:
            raise ViewGeometryError(f"affine must have 2 rows, got {len(row_values)}")
        first = _values(row_values[0], length=3, name="affine[0]")
        second = _values(row_values[1], length=3, name="affine[1]")
        return cls(*first, *second)

    def as_rows(self) -> tuple[tuple[float, float, float], tuple[float, float, float]]:
        return (
            (self.xx, self.xy, self.x_offset),
            (self.yx, self.yy, self.y_offset),
        )

    def map_point(self, point: Sequence[Real]) -> tuple[float, float]:
        x, y = _values(point, length=2, name="point")
        return (
            self.xx * x + self.xy * y + self.x_offset,
            self.yx * x + self.yy * y + self.y_offset,
        )

    def map_box(self, box: Sequence[Real]) -> tuple[float, float, float, float]:
        rect = RectXYXY.from_sequence(box, name="box")
        corners = (
            self.map_point((rect.x0, rect.y0)),
            self.map_point((rect.x1, rect.y0)),
            self.map_point((rect.x0, rect.y1)),
            self.map_point((rect.x1, rect.y1)),
        )
        xs = tuple(point[0] for point in corners)
        ys = tuple(point[1] for point in corners)
        return min(xs), min(ys), max(xs), max(ys)

    def inverse(self) -> "Affine2D":
        determinant = self.determinant
        inverse_xx = self.yy / determinant
        inverse_xy = -self.xy / determinant
        inverse_yx = -self.yx / determinant
        inverse_yy = self.xx / determinant
        inverse_x_offset = -(
            inverse_xx * self.x_offset + inverse_xy * self.y_offset
        )
        inverse_y_offset = -(
            inverse_yx * self.x_offset + inverse_yy * self.y_offset
        )
        return Affine2D(
            inverse_xx,
            inverse_xy,
            inverse_x_offset,
            inverse_yx,
            inverse_yy,
            inverse_y_offset,
        )


@dataclass(frozen=True)
class ViewGeometry:
    """Complete, task-independent registration metadata for one image view."""

    source_size_px: Size2D
    source_roi_xyxy_px: RectXYXY
    canvas_size_px: Size2D
    content_rect_canvas_xyxy_px: RectXYXY
    canvas_to_source: Affine2D

    def __post_init__(self) -> None:
        if not isinstance(self.source_size_px, Size2D):
            raise TypeError("source_size_px must be Size2D")
        if not isinstance(self.source_roi_xyxy_px, RectXYXY):
            raise TypeError("source_roi_xyxy_px must be RectXYXY")
        if not isinstance(self.canvas_size_px, Size2D):
            raise TypeError("canvas_size_px must be Size2D")
        if not isinstance(self.content_rect_canvas_xyxy_px, RectXYXY):
            raise TypeError("content_rect_canvas_xyxy_px must be RectXYXY")
        if not isinstance(self.canvas_to_source, Affine2D):
            raise TypeError("canvas_to_source must be Affine2D")

        source_extent = RectXYXY(0.0, 0.0, self.source_size_px.width, self.source_size_px.height)
        if not source_extent.contains_rect(self.source_roi_xyxy_px):
            raise GeometryConsistencyError(
                "source_roi_xyxy_px must lie fully inside source_size_px"
            )

        canvas_extent = RectXYXY(0.0, 0.0, self.canvas_size_px.width, self.canvas_size_px.height)
        if not canvas_extent.contains_rect(self.content_rect_canvas_xyxy_px):
            raise GeometryConsistencyError(
                "content_rect_canvas_xyxy_px must lie fully inside canvas_size_px"
            )

        self._validate_axis_aligned_registration()

    @classmethod
    def axis_aligned(
        cls,
        *,
        source_size_px: Sequence[Real],
        source_roi_xyxy_px: Sequence[Real],
        canvas_size_px: Sequence[Real],
        content_rect_canvas_xyxy_px: Sequence[Real],
    ) -> "ViewGeometry":
        """Build and record the affine for an axis-aligned resize/pad operation."""

        source_size = Size2D.from_pair(source_size_px, name="source_size_px")
        source_roi = RectXYXY.from_sequence(
            source_roi_xyxy_px, name="source_roi_xyxy_px"
        )
        canvas_size = Size2D.from_pair(canvas_size_px, name="canvas_size_px")
        content_rect = RectXYXY.from_sequence(
            content_rect_canvas_xyxy_px, name="content_rect_canvas_xyxy_px"
        )
        scale_x = source_roi.width / content_rect.width
        scale_y = source_roi.height / content_rect.height
        affine = Affine2D(
            scale_x,
            0.0,
            source_roi.x0 - scale_x * content_rect.x0,
            0.0,
            scale_y,
            source_roi.y0 - scale_y * content_rect.y0,
        )
        return cls(source_size, source_roi, canvas_size, content_rect, affine)

    @classmethod
    def from_metadata(cls, metadata: Mapping[str, Any]) -> "ViewGeometry":
        """Restore geometry while requiring every coordinate-contract field."""

        if metadata.get("local_coordinate_protocol") != LOCAL_COORDINATE_PROTOCOL:
            raise GeometryConsistencyError(
                "metadata must explicitly declare local_coordinate_protocol="
                f"{LOCAL_COORDINATE_PROTOCOL!r}"
            )
        return cls(
            source_size_px=Size2D.from_pair(
                metadata["source_size_px"], name="source_size_px"
            ),
            source_roi_xyxy_px=RectXYXY.from_sequence(
                metadata["source_roi_xyxy_px"], name="source_roi_xyxy_px"
            ),
            canvas_size_px=Size2D.from_pair(
                metadata["canvas_size_px"], name="canvas_size_px"
            ),
            content_rect_canvas_xyxy_px=RectXYXY.from_sequence(
                metadata["content_rect_canvas_xyxy_px"],
                name="content_rect_canvas_xyxy_px",
            ),
            canvas_to_source=Affine2D.from_rows(metadata["canvas_to_source_affine_2x3"]),
        )

    def to_metadata(self) -> dict[str, Any]:
        """Return the complete JSON-compatible view registration contract."""

        return {
            "source_size_px": list(self.source_size_px.as_pair()),
            "source_roi_xyxy_px": list(self.source_roi_xyxy_px.as_tuple()),
            "canvas_size_px": list(self.canvas_size_px.as_pair()),
            "content_rect_canvas_xyxy_px": list(
                self.content_rect_canvas_xyxy_px.as_tuple()
            ),
            "canvas_to_source_affine_2x3": [
                list(row) for row in self.canvas_to_source.as_rows()
            ],
            "local_coordinate_protocol": LOCAL_COORDINATE_PROTOCOL,
            "boundary_convention": BOUNDARY_CONVENTION,
        }

    def _validate_axis_aligned_registration(self) -> None:
        content = self.content_rect_canvas_xyxy_px
        source = self.source_roi_xyxy_px
        correspondences = (
            ((content.x0, content.y0), (source.x0, source.y0)),
            ((content.x1, content.y0), (source.x1, source.y0)),
            ((content.x0, content.y1), (source.x0, source.y1)),
            ((content.x1, content.y1), (source.x1, source.y1)),
        )
        for canvas_point, expected_source_point in correspondences:
            actual_source_point = self.canvas_to_source.map_point(canvas_point)
            for actual, expected in zip(actual_source_point, expected_source_point):
                if not math.isclose(actual, expected, rel_tol=1e-10, abs_tol=1e-8):
                    raise GeometryConsistencyError(
                        "canvas_to_source affine does not map content_rect_canvas_xyxy_px "
                        "to source_roi_xyxy_px: "
                        f"canvas point {canvas_point!r} mapped to {actual_source_point!r}, "
                        f"expected {expected_source_point!r}"
                    )

    @staticmethod
    def _strict_local_point(point: Sequence[Real]) -> tuple[float, float]:
        x, y = _values(point, length=2, name="local1000_point")
        return (
            _strict_base1000(x, name="local1000_point[0]"),
            _strict_base1000(y, name="local1000_point[1]"),
        )

    @staticmethod
    def _strict_local_box(box: Sequence[Real]) -> RectXYXY:
        values = _values(box, length=4, name="local1000_box")
        for index, value in enumerate(values):
            _strict_base1000(value, name=f"local1000_box[{index}]")
        return RectXYXY(*values)

    def _require_canvas_point_in_content(self, point: tuple[float, float]) -> None:
        if not self.content_rect_canvas_xyxy_px.contains_point(point):
            raise PaddingCoordinateError(
                f"canvas point {point!r} lies in padding outside content rectangle "
                f"{self.content_rect_canvas_xyxy_px.as_tuple()!r}"
            )

    def _require_canvas_box_in_content(self, rect: RectXYXY) -> None:
        if not self.content_rect_canvas_xyxy_px.contains_rect(rect):
            raise PaddingCoordinateError(
                f"canvas box {rect.as_tuple()!r} overlaps padding outside content rectangle "
                f"{self.content_rect_canvas_xyxy_px.as_tuple()!r}"
            )

    def _require_source_point_in_roi(self, point: tuple[float, float]) -> None:
        if not self.source_roi_xyxy_px.contains_point(point):
            raise CoordinateRangeError(
                f"source point {point!r} lies outside source ROI "
                f"{self.source_roi_xyxy_px.as_tuple()!r}"
            )

    def _require_source_box_in_roi(self, rect: RectXYXY) -> None:
        if not self.source_roi_xyxy_px.contains_rect(rect):
            raise CoordinateRangeError(
                f"source box {rect.as_tuple()!r} lies outside source ROI "
                f"{self.source_roi_xyxy_px.as_tuple()!r}"
            )

    def local1000_point_to_canvas_pixel(
        self, point: Sequence[Real]
    ) -> tuple[float, float]:
        x, y = self._strict_local_point(point)
        canvas_point = (
            x / LOCAL1000_SCALE * self.canvas_size_px.width,
            y / LOCAL1000_SCALE * self.canvas_size_px.height,
        )
        self._require_canvas_point_in_content(canvas_point)
        return canvas_point

    def local1000_box_to_canvas_pixel(
        self, box: Sequence[Real]
    ) -> tuple[float, float, float, float]:
        local_rect = self._strict_local_box(box)
        canvas_rect = RectXYXY(
            local_rect.x0 / LOCAL1000_SCALE * self.canvas_size_px.width,
            local_rect.y0 / LOCAL1000_SCALE * self.canvas_size_px.height,
            local_rect.x1 / LOCAL1000_SCALE * self.canvas_size_px.width,
            local_rect.y1 / LOCAL1000_SCALE * self.canvas_size_px.height,
        )
        self._require_canvas_box_in_content(canvas_rect)
        return canvas_rect.as_tuple()

    def local1000_point_to_source_pixel(
        self, point: Sequence[Real]
    ) -> tuple[float, float]:
        source_point = self._snap_source_point_to_roi(
            self.canvas_to_source.map_point(
                self.local1000_point_to_canvas_pixel(point)
            )
        )
        self._require_source_point_in_roi(source_point)
        return source_point

    def local1000_box_to_source_pixel(
        self, box: Sequence[Real]
    ) -> tuple[float, float, float, float]:
        source_box = self._snap_source_box_to_roi(
            self.canvas_to_source.map_box(
                self.local1000_box_to_canvas_pixel(box)
            )
        )
        source_rect = RectXYXY(*source_box)
        self._require_source_box_in_roi(source_rect)
        return source_rect.as_tuple()

    def _snap_source_point_to_roi(
        self, point: tuple[float, float]
    ) -> tuple[float, float]:
        """Correct arithmetic noise at declared ROI endpoints, never user input."""

        source = self.source_roi_xyxy_px
        return (
            self._snap_to_named_bounds(point[0], source.x0, source.x1),
            self._snap_to_named_bounds(point[1], source.y0, source.y1),
        )

    def _snap_source_box_to_roi(
        self, box: tuple[float, float, float, float]
    ) -> tuple[float, float, float, float]:
        source = self.source_roi_xyxy_px
        return (
            self._snap_to_named_bounds(box[0], source.x0, source.x1),
            self._snap_to_named_bounds(box[1], source.y0, source.y1),
            self._snap_to_named_bounds(box[2], source.x0, source.x1),
            self._snap_to_named_bounds(box[3], source.y0, source.y1),
        )

    def local1000_point_to_source1000(
        self, point: Sequence[Real]
    ) -> tuple[float, float]:
        x, y = self.local1000_point_to_source_pixel(point)
        return (
            _snap_generated_endpoint(x / self.source_size_px.width * LOCAL1000_SCALE, LOCAL1000_SCALE),
            _snap_generated_endpoint(y / self.source_size_px.height * LOCAL1000_SCALE, LOCAL1000_SCALE),
        )

    def local1000_box_to_source1000(
        self, box: Sequence[Real]
    ) -> tuple[float, float, float, float]:
        x0, y0, x1, y1 = self.local1000_box_to_source_pixel(box)
        return (
            _snap_generated_endpoint(x0 / self.source_size_px.width * LOCAL1000_SCALE, LOCAL1000_SCALE),
            _snap_generated_endpoint(y0 / self.source_size_px.height * LOCAL1000_SCALE, LOCAL1000_SCALE),
            _snap_generated_endpoint(x1 / self.source_size_px.width * LOCAL1000_SCALE, LOCAL1000_SCALE),
            _snap_generated_endpoint(y1 / self.source_size_px.height * LOCAL1000_SCALE, LOCAL1000_SCALE),
        )

    def _source_point_to_canvas_pixel(
        self, point: Sequence[Real]
    ) -> tuple[float, float]:
        source_point = _values(point, length=2, name="source_pixel_point")
        self._require_source_point_in_roi(source_point)
        canvas_point = self.canvas_to_source.inverse().map_point(source_point)
        return self._snap_canvas_point_to_content(canvas_point)

    def _source_box_to_canvas_pixel(
        self, box: Sequence[Real]
    ) -> tuple[float, float, float, float]:
        source_rect = RectXYXY.from_sequence(box, name="source_pixel_box")
        self._require_source_box_in_roi(source_rect)
        canvas_box = self.canvas_to_source.inverse().map_box(source_rect.as_tuple())
        return self._snap_canvas_box_to_content(canvas_box)

    def _snap_canvas_point_to_content(
        self, point: tuple[float, float]
    ) -> tuple[float, float]:
        content = self.content_rect_canvas_xyxy_px
        x = self._snap_to_named_bounds(point[0], content.x0, content.x1)
        y = self._snap_to_named_bounds(point[1], content.y0, content.y1)
        result = (x, y)
        self._require_canvas_point_in_content(result)
        return result

    def _snap_canvas_box_to_content(
        self, box: tuple[float, float, float, float]
    ) -> tuple[float, float, float, float]:
        content = self.content_rect_canvas_xyxy_px
        result = (
            self._snap_to_named_bounds(box[0], content.x0, content.x1),
            self._snap_to_named_bounds(box[1], content.y0, content.y1),
            self._snap_to_named_bounds(box[2], content.x0, content.x1),
            self._snap_to_named_bounds(box[3], content.y0, content.y1),
        )
        rect = RectXYXY(*result)
        self._require_canvas_box_in_content(rect)
        return rect.as_tuple()

    @staticmethod
    def _snap_to_named_bounds(value: float, lower: float, upper: float) -> float:
        tolerance = 1e-10 * max(1.0, abs(lower), abs(upper))
        if abs(value - lower) <= tolerance:
            return lower
        if abs(value - upper) <= tolerance:
            return upper
        return value

    def source_pixel_point_to_local1000(
        self, point: Sequence[Real]
    ) -> tuple[float, float]:
        x, y = self._source_point_to_canvas_pixel(point)
        return (
            _snap_generated_endpoint(x / self.canvas_size_px.width * LOCAL1000_SCALE, LOCAL1000_SCALE),
            _snap_generated_endpoint(y / self.canvas_size_px.height * LOCAL1000_SCALE, LOCAL1000_SCALE),
        )

    def source_pixel_box_to_local1000(
        self, box: Sequence[Real]
    ) -> tuple[float, float, float, float]:
        x0, y0, x1, y1 = self._source_box_to_canvas_pixel(box)
        return (
            _snap_generated_endpoint(x0 / self.canvas_size_px.width * LOCAL1000_SCALE, LOCAL1000_SCALE),
            _snap_generated_endpoint(y0 / self.canvas_size_px.height * LOCAL1000_SCALE, LOCAL1000_SCALE),
            _snap_generated_endpoint(x1 / self.canvas_size_px.width * LOCAL1000_SCALE, LOCAL1000_SCALE),
            _snap_generated_endpoint(y1 / self.canvas_size_px.height * LOCAL1000_SCALE, LOCAL1000_SCALE),
        )

    def source1000_point_to_local1000(
        self, point: Sequence[Real]
    ) -> tuple[float, float]:
        x, y = self._strict_source1000_point(point)
        return self.source_pixel_point_to_local1000(
            (
                x / LOCAL1000_SCALE * self.source_size_px.width,
                y / LOCAL1000_SCALE * self.source_size_px.height,
            )
        )

    def source1000_box_to_local1000(
        self, box: Sequence[Real]
    ) -> tuple[float, float, float, float]:
        rect = self._strict_source1000_box(box)
        return self.source_pixel_box_to_local1000(
            (
                rect.x0 / LOCAL1000_SCALE * self.source_size_px.width,
                rect.y0 / LOCAL1000_SCALE * self.source_size_px.height,
                rect.x1 / LOCAL1000_SCALE * self.source_size_px.width,
                rect.y1 / LOCAL1000_SCALE * self.source_size_px.height,
            )
        )

    @staticmethod
    def _strict_source1000_point(point: Sequence[Real]) -> tuple[float, float]:
        x, y = _values(point, length=2, name="source1000_point")
        return (
            _strict_base1000(x, name="source1000_point[0]"),
            _strict_base1000(y, name="source1000_point[1]"),
        )

    @staticmethod
    def _strict_source1000_box(box: Sequence[Real]) -> RectXYXY:
        values = _values(box, length=4, name="source1000_box")
        for index, value in enumerate(values):
            _strict_base1000(value, name=f"source1000_box[{index}]")
        return RectXYXY(*values)


